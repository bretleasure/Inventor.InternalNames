using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace ExtractInternalNames.Core;

public static class SourceGenerator
{
    public static IReadOnlyDictionary<string, string> Generate(NameCatalog catalog, ISet<string> categories = null)
    {
        catalog.Validate();
        var files = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (var file in catalog.Groups.GroupBy(g => g.File).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            // A file belongs to a category; do not partially regenerate a shared file.
            if (categories != null && !file.Any(g => categories.Contains(g.Category))) continue;
            var sb = new StringBuilder();
            sb.Append("// <auto-generated />\n// Update with ExtractInternalNames; public names are stored in Names.xml.\n\n");
            sb.Append("namespace ").Append(file.First().Namespace).Append("\n{\n");
            RenderClasses(sb, file.ToList(), "", 1);
            sb.Append("}\n");
            files.Add(file.Key, sb.ToString());
        }
        ValidateCompilation(files);
        return files;
    }

    private static void RenderClasses(StringBuilder sb, List<NameGroup> groups, string parent, int depth)
    {
        var children = groups.Select(g => g.Class).Where(c => c.StartsWith(parent, StringComparison.Ordinal))
            .Select(c => c.Substring(parent.Length).Split('.')[0]).Distinct(StringComparer.Ordinal)
            .OrderBy(c => c, StringComparer.Ordinal);
        foreach (var name in children)
        {
            var path = parent + name;
            var indent = new string(' ', depth * 4);
            sb.Append(indent).Append("public static class ").Append(name).Append("\n").Append(indent).Append("{\n");
            var group = groups.SingleOrDefault(g => g.Class == path);
            if (group != null)
                foreach (var entry in group.Names.OrderBy(n => n.Name, StringComparer.Ordinal))
                    sb.Append(indent).Append("    public const string ").Append(entry.Name).Append(" = ")
                        .Append(SymbolDisplay.FormatLiteral(entry.Value, quote: true)).Append(";\n");
            RenderClasses(sb, groups.Where(g => g.Class.StartsWith(path + ".", StringComparison.Ordinal)).ToList(),
                path + ".", depth + 1);
            sb.Append(indent).Append("}\n");
        }
    }

    public static void ValidateCompilation(IReadOnlyDictionary<string, string> files)
    {
        var trees = files.Select(f => CSharpSyntaxTree.ParseText(f.Value, path: f.Key));
        var compilation = CSharpCompilation.Create("GeneratedNames", trees,
            new[] { MetadataReference.CreateFromFile(typeof(object).Assembly.Location) },
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));
        var errors = compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToArray();
        if (errors.Length != 0)
            throw new InvalidDataException("Generated source failed validation:\n" + string.Join("\n", errors.Select(e => e.ToString())));
    }
}
